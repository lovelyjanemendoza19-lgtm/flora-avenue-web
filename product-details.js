const params = new URLSearchParams(window.location.search);

const productId = params.get("id");

const product = products[productId];


const productName =
    document.getElementById("productName");

const productDescription =
    document.getElementById("productDescription");

const productImage =
    document.getElementById("productImage");

const variationSelect =
    document.getElementById("variationSelect");

const colorSelect =
    document.getElementById("colorSelect");

const colorGroup =
    document.getElementById("colorGroup");

const productPrice =
    document.getElementById("productPrice");

const totalPrice =
    document.getElementById("totalPrice");


if (!product) {

    productName.textContent =
        "Product Not Found";

} else {

    productName.textContent =
        product.name;

    productDescription.textContent =
        product.description;


    /* ADD VARIATIONS */

    product.variations.forEach(function (variation) {

        const option =
            document.createElement("option");

        option.value =
            variation.value;

        option.textContent =
            variation.name;

        variationSelect.appendChild(option);

    });


    /* ADD COLORS */

    if (product.colors.length === 0) {

        colorGroup.style.display =
            "none";

    } else {

        product.colors.forEach(function (color) {

            const option =
                document.createElement("option");

            option.value =
                color;

            option.textContent =
                color.charAt(0).toUpperCase() +
                color.slice(1);

            colorSelect.appendChild(option);

        });

    }


    updateProduct();
}

function updateProduct() {

    if (!product) {
        return;
    }


    const variationValue =
        variationSelect.value;

    const colorValue =
        colorSelect.value;


    const selectedVariation =
        product.variations.find(function (variation) {

            return variation.value === variationValue;

        });


    if (!selectedVariation) {
        return;
    }


    /* PRICE */

    productPrice.textContent =
        "₱" + selectedVariation.price.toLocaleString();


    /* IMAGE */

    if (product.colors.length > 0) {

        productImage.src =
            "images/" +
            product.folder +
            "/" +
            variationValue +
            "-" +
            colorValue +
            ".jpg";

    } else {

        productImage.src =
            "images/" +
            product.folder +
            "/" +
            variationValue +
            ".jpg";

    }


    updateTotal();
}

variationSelect.addEventListener(
    "change",
    updateProduct
);

colorSelect.addEventListener(
    "change",
    updateProduct
);

const addonCheckboxes =
    document.querySelectorAll(
        '.addons input[type="checkbox"]'
    );


addonCheckboxes.forEach(function (checkbox) {

    checkbox.addEventListener(
        "change",
        updateTotal
    );

});


function updateTotal() {

    if (!product) {
        return;
    }


    const variationValue =
        variationSelect.value;


    const selectedVariation =
        product.variations.find(function (variation) {

            return variation.value === variationValue;

        });


    let total =
        selectedVariation.price;


    addonCheckboxes.forEach(function (checkbox) {

        if (checkbox.checked) {

            total +=
                Number(checkbox.value);

        }

    });


    totalPrice.textContent =
        "₱" + total.toLocaleString();
}

const mainActionButton =
    document.getElementById("mainActionButton");

    if (product.type === "customized") {

    mainActionButton.textContent = "Customized";

    mainActionButton.onclick = function () {
        window.location.href =
            "customized.html?id=" + productId;
    };

} else {

    mainActionButton.textContent = "Order";

    mainActionButton.onclick = function () {
        window.location.href =
            "order.html?id=" + productId;
    };

}

